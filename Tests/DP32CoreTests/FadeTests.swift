    private func check(_ rows: [(Int32, Int32, Int, Int32)], file: StaticString = #filePath, line: UInt = #line) {
        for (a, b, i, expected) in rows {
            XCTAssertEqual(fade.mix(outgoing: a, incoming: b, at: i), expected,
                           "outgoing \(a), incoming \(b), index \(i)", file: file, line: line)
        }
    }

    func testFadeInMatchesHardware() { check(FadeTests.fadeIn) }
    func testFadeOutMatchesHardware() { check(FadeTests.fadeOut) }
    func testCrossfadeMatchesHardware() { check(FadeTests.crossfade) }

    func testKnownOneLSBDifferencesAreStillExactlyThese() {
        for (a, b, i, hardware, ours) in FadeTests.knownMisses {
            XCTAssertEqual(fade.mix(outgoing: a, incoming: b, at: i), ours)
            XCTAssertEqual(abs(Int(hardware) - Int(ours)), 1)
        }
    }

    func testSilenceStaysSilent() {
        for i in 0..<480 { XCTAssertEqual(fade.mix(outgoing: 0, incoming: 0, at: i), 0) }
    }

    func testFadeInStartsAtZeroAndFadeOutEndsNearZero() {
        XCTAssertEqual(fade.mix(outgoing: 0, incoming: 8_000_000, at: 0), 0)
        XCTAssertEqual(fade.mix(outgoing: 0, incoming: -8_000_000, at: 0), 0)
        XCTAssertLessThan(abs(fade.mix(outgoing: 8_000_000, incoming: 0, at: 479)), 17_000)
    }

    func testTablesFor441() {
        let f = EdgeFade(length: 441)
        XCTAssertEqual(f.gainIn[0], 0)
        XCTAssertEqual(f.gainOut[0], (Int64(1) << 31) - 1)
        XCTAssertEqual(f.gainIn[440], (0x7FFFFF * 440 * 440) / (441 * 441))
        XCTAssertEqual(f.gainOut[440], (Int64(1) << 31) / 441)
    }
